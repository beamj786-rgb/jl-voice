"""Render audit-lines.jsonl (printed by dump_reports.py) as a per-recording transcript table."""
import json
import pathlib
import sys

def main():
    source, output = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    lines = [(l.split(' ', 1)[0], json.loads(l.split(' ', 1)[1])) for l in source.read_text(encoding='utf-8').splitlines() if l.strip()]
    reports = {d['file']: d for t, d in lines if t == 'AUDIT_REPORT'}
    samples = [d for t, d in lines if t == 'AUDIT_SAMPLE']
    refs = {}
    for t, d in lines:
        if t == 'AUDIT_REFERENCE': refs.setdefault(d['id'], d)
    runs = sorted({f.split('/')[0] for f in reports})
    out = ['# Czech decoding experiment: per-recording transcripts', '',
           'Generated by `benchmarks/audit_tables.py` from `audit-lines.jsonl` (CI job printing the stt-experiment artifacts of runs '
           + ', '.join(runs) + '). Public FLEURS dev read speech (CC-BY-4.0) and synthetic controls only.', '',
           'Runner CPUs: ' + '; '.join(f"{r}: {next(d['cpu'] for f, d in reports.items() if f.startswith(r))}" for r in runs), '',
           'Scoring (`benchmarks/score.py`): NFC + casefold; tokens = `[^\\W_]+(?:[\'’][^\\W_]+)*` (punctuation dropped, diacritics kept); '
           'word Levenshtein gives S/D/I; CER = character Levenshtein on tokens joined by single spaces. Group WER = ΣS+D+I / Σref words; '
           'group CER = Σchar errors / Σref chars (both summed per recording, not averaged). Controls have empty references: every output word counts as hallucinated.', '',
           'audio_ctx 0 = full 30 s window (1500 frames); otherwise min(1500, floor(s×50)+128).', '']
    order = sorted(refs, key=lambda i: (refs[i].get('group', refs[i]['language']), i))
    for rid in order:
        ref = refs[rid]
        out += [f"## {rid} ({ref.get('group', ref['language'])})", '', f"Reference: {ref['reference'] or '(none – control)'}", '',
                '| Run / config | s | audio_ctx | S/D/I of words | char err / chars | Transcript |', '|---|---:|---:|---|---|---|']
        for s in sorted((s for s in samples if s['id'] == rid), key=lambda s: s['file']):
            sc = s['score']
            text = s['text'].replace('|', '\\|')
            out.append(f"| {s['file'][:-5]} | {s['audio_seconds']:.2f} | {s['audio_ctx']} | {sc['substitutions']}/{sc['deletions']}/{sc['insertions']} of {sc['words']} "
                       f"| {sc['character_errors']}/{sc['characters']} | {text} |")
        out.append('')
    output.write_text('\n'.join(out), encoding='utf-8')

if __name__ == '__main__': main()
