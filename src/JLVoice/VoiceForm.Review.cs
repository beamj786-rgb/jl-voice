using System.Drawing.Imaging;
using System.Text.Json;

namespace JLVoice;

internal sealed partial class VoiceForm
{
    // Explicit development-only render checks: no audio, ASR, hotkeys, clipboard or user transcripts.
    internal void ExportUiReview(string directory)
    {
        if (!reviewMode) throw new InvalidOperationException("UI review must be explicitly requested at startup.");
        directory = Path.GetFullPath(directory); Directory.CreateDirectory(directory);
        var issues = new List<string>();
        var states = new List<object>();
        void Capture(string name)
        {
            PerformLayout(); Application.DoEvents(); Refresh();
            using var bitmap = new Bitmap(ClientSize.Width, ClientSize.Height);
            DrawToBitmap(bitmap, new Rectangle(Point.Empty, ClientSize)); bitmap.Save(Path.Combine(directory, name + ".png"), ImageFormat.Png);
            void Inspect(Control control)
            {
                if (!control.Visible) return;
                if (control is not Form && control.Parent is { } parent && parent is not ScrollableControl { AutoScroll: true } &&
                    (control.Right > parent.ClientSize.Width + 3 || control.Left < -3))
                    issues.Add($"{name}: horizontal clipping: {control.GetType().Name} '{control.Text}' ({control.Bounds}, parent {parent.ClientSize})");
                foreach (Control child in control.Controls) Inspect(child);
            }
            Inspect(this);
            states.Add(new { name, width = ClientSize.Width, height = ClientSize.Height, language = uiLanguage, theme = SelectedTheme, page = currentPage });
        }
        if (!BrandFonts.AllLoaded || BrandFonts.Get("body", 10).FontFamily.Name != "Funnel Sans" ||
            !BrandFonts.Get("display", 28).FontFamily.Name.StartsWith("Funnel Display", StringComparison.Ordinal) || BrandFonts.Get("mono", 10).FontFamily.Name != "Geist Mono")
            issues.Add("One or more bundled brand fonts failed to load.");
        foreach (var light in new[] { false, true })
        {
            theme.SelectedIndex = light ? 1 : 0; interfaceLanguage.SelectedIndex = 0;
            ClientSize = new Size(940, 720); Navigate(0); Capture(light ? "light-overview" : "dark-overview");
            settingsNav.PerformClick();
            if (currentPage != 1 || !preferences.Visible) issues.Add("Settings navigation failed.");
            Capture(light ? "light-settings" : "dark-settings");
        }
        theme.SelectedIndex = 0; interfaceLanguage.SelectedIndex = 1; ClientSize = new Size(800, 580);
        overviewNav.PerformClick(); Capture("compact-english-overview"); settingsNav.PerformClick(); Capture("compact-english-settings");
        preferences.AutoScrollPosition = new Point(0, preferences.DisplayRectangle.Height); Capture("compact-english-settings-bottom");
        preferences.AutoScrollPosition = Point.Empty;
        overlay.SetStatus("Nahrávání · UI test", "12 s"); overlay.Show(); Application.DoEvents();
        using (var bitmap = new Bitmap(overlay.Width, overlay.Height))
        {
            overlay.DrawToBitmap(bitmap, overlay.ClientRectangle);
            bitmap.Save(Path.Combine(directory, "overlay-recording-fixture.png"), ImageFormat.Png);
        }
        overlay.Hide();
        // Exercise native keyboard focus traversal, not a custom DOM approximation.
        Navigate(1); language.Focus(); SelectNextControl(language, true, true, true, true);
        if (!ContainsFocus) issues.Add("Keyboard traversal left the application.");
        if (!string.IsNullOrEmpty(result.Text)) issues.Add("UI review unexpectedly contains a transcript.");
        File.WriteAllText(Path.Combine(directory, "review.json"), JsonSerializer.Serialize(new
        {
            fonts_loaded = BrandFonts.AllLoaded, states, issues,
            limits = new[] { "Native DrawToBitmap captures; physical multi-monitor DPI and screen-reader acceptance remain unverified.",
                "No real audio or transcription was generated by UI review.", "Compact viewport exercises layout and scrolling; it is not a real 150/200 percent DPI test." }
        }, new JsonSerializerOptions { WriteIndented = true }));
        if (issues.Count != 0) throw new InvalidOperationException(string.Join(Environment.NewLine, issues));
    }
}
